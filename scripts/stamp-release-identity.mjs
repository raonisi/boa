import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const FULL_SHA_PATTERN = /^[0-9a-f]{40}$/;
const DEFAULT_OUTPUT_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../server/generated/releaseIdentity.ts"
);

export class ReleaseIdentityError extends Error {
  constructor(code) {
    super(code);
    this.name = "ReleaseIdentityError";
    this.code = code;
  }
}

export function validateReleaseSha(value) {
  if (typeof value !== "string" || !FULL_SHA_PATTERN.test(value)) {
    throw new ReleaseIdentityError("INVALID_RELEASE_SHA");
  }
  return value;
}

export function renderReleaseIdentity(value) {
  const releaseSha = validateReleaseSha(value);
  return [
    "// Generated by scripts/stamp-release-identity.mjs. Do not edit during deployment.",
    `export const RELEASE_SHA: string = ${JSON.stringify(releaseSha)};`,
    "",
  ].join("\n");
}

export async function stampReleaseIdentity({
  releaseSha,
  outputPath = DEFAULT_OUTPUT_PATH,
}) {
  const rendered = renderReleaseIdentity(releaseSha);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, rendered, "utf8");
  return { releaseSha, outputPath };
}

export async function verifyReleaseIdentity({
  releaseSha,
  outputPath = DEFAULT_OUTPUT_PATH,
}) {
  const expected = renderReleaseIdentity(releaseSha);
  const actual = await readFile(outputPath, "utf8");
  if (actual !== expected) {
    throw new ReleaseIdentityError("RELEASE_IDENTITY_MISMATCH");
  }
  return { releaseSha, outputPath };
}

async function runCli() {
  const args = process.argv.slice(2);
  const releaseSha = args[0];
  const verify = args.includes("--verify");
  const outputIndex = args.indexOf("--output");
  const outputPath =
    outputIndex >= 0 ? resolve(args[outputIndex + 1] ?? "") : DEFAULT_OUTPUT_PATH;
  if (outputIndex >= 0 && !args[outputIndex + 1]) {
    throw new ReleaseIdentityError("OUTPUT_PATH_MISSING");
  }

  const result = verify
    ? await verifyReleaseIdentity({ releaseSha, outputPath })
    : await stampReleaseIdentity({ releaseSha, outputPath });
  console.log(JSON.stringify({ ok: true, releaseSha: result.releaseSha }));
}

const isDirectExecution =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectExecution) {
  runCli().catch(error => {
    const code =
      error instanceof ReleaseIdentityError
        ? error.code
        : "RELEASE_IDENTITY_FAILED";
    console.error(JSON.stringify({ ok: false, code }));
    process.exitCode = 1;
  });
}
